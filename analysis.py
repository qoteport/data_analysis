# Feature Selection Parameters
FEATURE_SELECTION_METHOD = 'mutual_info'  # 'mutual_info', 'chi2', 'rf', 'lasso', 'pca'
TOP_K_FEATURES = 30  # Number of top features to select
SELECT_FEATURES_AFTER_PREPROCESSING = True

