    def _store_training_history(self):
        """Store training history"""
        if self.history is not None:
            history = self.history.history
            self.training_history['epochs'] = list(range(1, len(history['loss']) + 1))
            self.training_history['train_loss'] = history['loss']
            self.training_history['val_loss'] = history['val_loss']
            self.training_history['train_accuracy'] = history['accuracy']
            self.training_history['val_accuracy'] = history['val_accuracy']

    def predict(self, X):
        """Make predictions"""
        if not self.is_trained:
            raise ValueError(f"{self.name} model is not trained")

        safe_batch_size = MemoryManager.calculate_safe_batch_size(X, BATCH_SIZE)
        return self.model.predict(X, verbose=0, batch_size=safe_batch_size).flatten()

