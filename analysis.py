    actual_target_col_name = preprocessor.actual_target_col_name
    X, y, dates, feature_names = prepare_time_series_data(df_processed, target_col=actual_target_col_name)

    # Split data using stratified sampling to ensure balanced class distribution
    # This prevents validation/test sets from being all 0s or all 1s
    from sklearn.model_selection import StratifiedShuffleSplit
    
    sss = StratifiedShuffleSplit(n_splits=1, test_size=TEST_SIZE, random_state=42)
    train_val_indices, test_indices = next(sss.split(X, y))
    
    X_train_val, X_test = X[train_val_indices], X[test_indices]
    y_train_val, y_test = y[train_val_indices], y[test_indices]
    dates_train_val, dates_test = dates[train_val_indices], dates[test_indices]
    
    # Further stratified split of train_val into train and validation
    sss_val = StratifiedShuffleSplit(n_splits=1, test_size=VALIDATION_SPLIT, random_state=42)
    train_indices, val_indices = next(sss_val.split(X_train_val, y_train_val))
    
    X_train, X_val = X_train_val[train_indices], X_train_val[val_indices]
    y_train, y_val = y_train_val[train_indices], y_train_val[val_indices]
    dates_train, dates_val = dates_train_val[train_indices], dates_train_val[val_indices]

    print(f"\nData Split:")
    print(f"  Train: {X_train.shape} ({len(y_train)} samples)")
    print(f"  Validation: {X_val.shape} ({len(y_val)} samples)")
    print(f"  Test: {X_test.shape} ({len(y_test)} samples)")

    # Sanity checks on targets
    try:
        unique_train, counts_train = np.unique(y_train, return_counts=True)
        unique_val, counts_val = np.unique(y_val, return_counts=True)
        unique_test, counts_test = np.unique(y_test, return_counts=True)
        print(f"\nTarget distribution:\n  Train: {dict(zip(unique_train, counts_train))}\n  Val: {dict(zip(unique_val, counts_val))}\n  Test: {dict(zip(unique_test, counts_test))}")
    except Exception:
        pass

    # Store data for later use
    data_dict = {
        'X_train': X_train, 'y_train': y_train,
        'X_val': X_val, 'y_val': y_val,
        'X_test': X_test, 'y_test': y_test,
        'dates_train': dates_train, 'dates_val': dates_val,
        'dates_test': dates_test,
        'feature_names': feature_names,
        'preprocessor': preprocessor
    }

    # Initialize PhD-enhanced pipeline
    pipeline = PhDEnhancedModelPipeline()
    pipeline.data = data_dict

    # 1. Train individual models
    print("\n" + "="*80)
    print("PHASE 1: TRAINING INDIVIDUAL MODELS")
    print("="*80)
    pipeline.train_all_models(X_train, y_train, X_val, y_val, dates_train, dates_val)
    pipeline.evaluate_all_models(y_train, y_val)

    # 2. Create and train regular hybrids
    print("\n" + "="*80)
    print("PHASE 2: CREATING REGULAR HYBRIDS")
    print("="*80)
    pipeline.create_hybrids()

    # 3. Create and train enhanced residual hybrids (FIXED)
    print("\n" + "="*80)
    print("PHASE 3: CREATING ENHANCED RESIDUAL HYBRIDS (COMPREHENSIVE)")
    print("="*80)
    pipeline.create_enhanced_residual_hybrids()

    # 4. Create and train ensemble hybrids with composition tracking
    print("\n" + "="*80)
    print("PHASE 4: CREATING ENSEMBLE HYBRIDS")
    print("="*80)
    pipeline.create_ensemble_hybrids()

    # 5. Train all hybrid types
    print("\n" + "="*80)
