    print("\n\n2. TIME SERIES PREPARATION")
    print("-"*40)

    actual_target_col_name = preprocessor.actual_target_col_name
    X, y, dates, feature_names = prepare_time_series_data(df_processed, target_col=actual_target_col_name)

    # Split data using stratified sampling to ensure balanced class distribution
    # This prevents validation/test sets from being all 0s or all 1s
    from sklearn.model_selection import StratifiedShuffleSplit
    
    sss = StratifiedShuffleSplit(n_splits=1, test_size=TEST_SIZE, random_state=42)
    train_val_indices, test_indices = next(sss.split(X, y))
    
    X_train_val, X_test = X[train_val_indices], X[test_indices]
    y_train_val, y_test = y[train_val_indices], y[test_indices]
    dates_train_val, dates_test = dates[train_val_indices], dates[test_indices]
    
    # Further stratified split of train_val into train and validation
    sss_val = StratifiedShuffleSplit(n_splits=1, test_size=VALIDATION_SPLIT, random_state=42)
    train_indices, val_indices = next(sss_val.split(X_train_val, y_train_val))
    
    X_train, X_val = X_train_val[train_indices], X_train_val[val_indices]
    y_train, y_val = y_train_val[train_indices], y_train_val[val_indices]
    dates_train, dates_val = dates_train_val[train_indices], dates_train_val[val_indices]

