class MemoryManager:
    """Centralized memory management for TensorFlow/Keras models"""

    @staticmethod
    def initialize():
        """Initialize TensorFlow with memory optimizations"""
        try:
            # Clear any existing sessions
            K.clear_session()
            tf.compat.v1.reset_default_graph()

            # Configure GPU memory growth
            gpus = tf.config.experimental.list_physical_devices('GPU')
            if gpus:
                for gpu in gpus:
                    tf.config.experimental.set_memory_growth(gpu, True)
                print(f"✓ GPU memory growth enabled on {len(gpus)} GPU(s)")

            # Set mixed precision if available
            try:
                policy = tf.keras.mixed_precision.Policy('mixed_float16')
                tf.keras.mixed_precision.set_global_policy(policy)
                print("✓ Mixed precision enabled")
            except:
                pass

            # Optimize TensorFlow performance
            tf.config.threading.set_intra_op_parallelism_threads(2)
            tf.config.threading.set_inter_op_parallelism_threads(2)

        except Exception as e:
            print(f"⚠ Memory initialization warning: {e}")

    @staticmethod
    def cleanup():
        """Force cleanup of memory"""
        gc.collect()
        K.clear_session()
        tf.compat.v1.reset_default_graph()

    @staticmethod
    def get_memory_usage():
        """Get current memory usage in MB"""
        process = psutil.Process(os.getpid())
        return process.memory_info().rss / 1024 ** 2

    @staticmethod
    def validate_data(X_train, y_train, X_val, y_val):
        """Validate data shapes and clean data"""
        print("📊 Data Validation:")

        # Check shapes
        print(f"  X_train shape: {X_train.shape}")
        print(f"  y_train shape: {y_train.shape}")
        print(f"  X_val shape: {X_val.shape}")
        print(f"  y_val shape: {y_val.shape}")

        # Validate 3D shape for sequence models
        if len(X_train.shape) != 3:
            raise ValueError(f"X_train must be 3D (samples, timesteps, features). Got: {X_train.shape}")

        # Check for NaN/Inf
        train_nan = np.isnan(X_train).sum()
        train_inf = np.isinf(X_train).sum()

        if train_nan > 0 or train_inf > 0:
            print(f"  ⚠ Cleaning {train_nan} NaN and {train_inf} Inf values")
            X_train = np.nan_to_num(X_train, nan=0.0, posinf=1.0, neginf=-1.0)
            X_val = np.nan_to_num(X_val, nan=0.0, posinf=1.0, neginf=-1.0)

        # Check sequence length
        if X_train.shape[1] > 500:
            print(f"  ⚠ Long sequence length: {X_train.shape[1]}. Consider reducing.")

        # Check class balance
        unique, counts = np.unique(y_train, return_counts=True)
        if len(unique) == 2:
            ratio = counts[1] / counts[0] if counts[0] > 0 else float('inf')
            if ratio < 0.2 or ratio > 5:
                print(f"  ⚠ Class imbalance detected: Class 0={counts[0]}, Class 1={counts[1]}")

        print("  ✓ Data validation complete")
        return X_train, X_val

    @staticmethod
    def calculate_safe_batch_size(X_train, default_batch_size=32):
        """Calculate safe batch size based on data size"""
        n_samples = len(X_train)
        seq_length = X_train.shape[1]
        n_features = X_train.shape[2]

        # Estimate memory per sample
        estimated_memory_per_sample = seq_length * n_features * 4  # 4 bytes per float32

        # Calculate safe batch size
        safe_batch = min(default_batch_size, n_samples // 4)
        safe_batch = max(8, safe_batch)  # Minimum batch size

        # Adjust based on sequence length
        if seq_length > 100:
            safe_batch = max(8, safe_batch // 2)

        return safe_batch

