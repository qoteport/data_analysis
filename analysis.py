    def _cache_paths(self):
        """Return standard paths for cache, model and checkpoint files."""
        base = os.path.abspath(os.path.curdir)
        cache_dir = os.path.join(base, 'cache')
        models_dir = os.path.join(base, 'models')
        checkpoints_dir = os.path.join(base, 'checkpoints')
        os.makedirs(cache_dir, exist_ok=True)
        os.makedirs(models_dir, exist_ok=True)
        os.makedirs(checkpoints_dir, exist_ok=True)

        name = self.name.lower().replace(' ', '_')
        # include cache version hash to avoid stale caches when config or architecture changes
        try:
            version = self.get_cache_version()
            suffix = f"_{version}"
        except Exception:
            suffix = ''

        preds_path = os.path.join(cache_dir, f'{name}{suffix}_predictions.npz')
        history_path = os.path.join(cache_dir, f'{name}{suffix}_history.json')
        model_path = os.path.join(models_dir, f'{name}{suffix}.pkl')
        weights_path = os.path.join(checkpoints_dir, f'best_{name}{suffix}.weights.h5')

        return {
            'cache_dir': cache_dir,
            'models_dir': models_dir,
            'checkpoints_dir': checkpoints_dir,
            'preds': preds_path,
            'history': history_path,
            'model': model_path,
            'weights': weights_path
        }

    def get_cache_version(self):
        """Compute a short hash representing model+training config to version cache files."""
        try:
            cfg = {
                'name': self.name,
                'arch': getattr(self, 'architecture_info', {}),
                'params': {
                    'epochs': EPOCHS,
                    'batch_size': BATCH_SIZE,
                    'learning_rate': LEARNING_RATE,
                    'lstm_units': LSTM_UNITS,
                    'dense_units': DENSE_UNITS,
                }
            }
            s = json.dumps(cfg, sort_keys=True, default=str)
            h = hashlib.md5(s.encode('utf-8')).hexdigest()[:8]
            return h
        except Exception:
            return ''

    def save_cache(self):
        """Save predictions and training history and, where applicable, the model file."""
        paths = self._cache_paths()
        try:
            # Save predictions if available
            preds = {}
            for k, v in self.predictions.items():
                try:
                    preds[k] = np.array(v)
                except:
                    continue
            if preds:
                np.savez_compressed(paths['preds'], **preds)

            # Save training history
            try:
                with open(paths['history'], 'w') as f:
                    json.dump(self.training_history, f, default=lambda o: list(o) if hasattr(o, '__iter__') else str(o))
            except Exception:
                pass

            # Save sklearn/xgboost model via joblib if present and not a Keras model
            try:
                if hasattr(self.model, 'fit') and not hasattr(self.model, 'save_weights'):
                    joblib.dump(self.model, paths['model'])
            except Exception:
                pass
        except Exception as e:
            print(f"⚠ Could not save cache for {self.name}: {e}")

    def load_cache_if_available(self, X_train=None, y_train=None, X_val=None, y_val=None):
        """Attempt to load model/predictions from cache. Returns True if loaded."""
        paths = self._cache_paths()

        # If predictions and history exist, load them and try to load model weights if applicable
        if os.path.exists(paths['preds']) and os.path.exists(paths['history']):
            try:
                npz = np.load(paths['preds'])
                # Validate cached prediction lengths against provided data to avoid stale cache reuse
                cached = {k: npz[k] for k in npz.files}

                # Determine expected lengths
                expected_train_len = None
                expected_val_len = None
                if X_train is not None:
                    try:
                        expected_train_len = int(X_train.shape[0])
                    except Exception:
                        pass
                if y_train is not None and expected_train_len is None:
                    try:
                        expected_train_len = int(len(y_train))
                    except Exception:
                        pass
                if X_val is not None:
                    try:
                        expected_val_len = int(X_val.shape[0])
                    except Exception:
                        pass
                if y_val is not None and expected_val_len is None:
                    try:
                        expected_val_len = int(len(y_val))
                    except Exception:
                        pass

                # Check cached arrays lengths
                valid_cache = True
                if 'train' in cached and expected_train_len is not None:
                    if int(cached['train'].shape[0]) != expected_train_len:
                        valid_cache = False
                if 'val' in cached and expected_val_len is not None:
                    if int(cached['val'].shape[0]) != expected_val_len:
                        valid_cache = False

                if not valid_cache:
                    print(f"  ⚠ Cached predictions length mismatch for {self.name}; ignoring cache.")
                    return False

                for k, v in cached.items():
                    self.predictions[k] = v

                try:
                    with open(paths['history'], 'r') as f:
                        self.training_history = json.load(f)
                except Exception:
                    pass

                # Try loading model: Keras weights or joblib model
                if os.path.exists(paths['weights']) and hasattr(self, 'build_model'):
                    try:
                        # Build architecture if needed
                        if self.model is None and hasattr(self, 'build_model') and X_train is not None:
                            input_shape = (X_train.shape[1], X_train.shape[2]) if X_train is not None and X_train.ndim == 3 else (X_train.shape[1],)
                            try:
                                self.model = self.build_model(input_shape)
                            except Exception:
                                pass
                        if self.model is not None:
                            self.model.load_weights(paths['weights'])
                    except Exception:
                        pass
                elif os.path.exists(paths['model']):
                    try:
                        self.model = joblib.load(paths['model'])
                    except Exception:
                        pass

                self.is_trained = True
                print(f"  ✓ Loaded cached results for {self.name} from {paths['cache_dir']}")
                return True
            except Exception as e:
                print(f"  ⚠ Failed to load cache for {self.name}: {e}")
                return False

        return False

